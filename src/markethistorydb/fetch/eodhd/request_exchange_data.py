#!/usr/bin/env python12.9

"""Class for requesting exchange data from eodhd.com"""

import pandas as pd

from markethistorydb.db                       import tables
from markethistorydb.fetch.eodhd.errors       import CompatibilityError
from markethistorydb.fetch.eodhd.request_data import RequestData
from markethistorydb.fetch.eodhd.url          import Url
from markethistorydb.utils         import TimeFrame


# Exchanges to download daily and intraday data from
_EXCHANGE_NAMES_EOD    = ["USA Stocks", "London Exchange", "Toronto Exchange", "XETRA Stock Exchange",
                         "Shanghai Stock Exchange", "FOREX", "Cryptocurrencies",
                         "Government Bonds"]
_EXCHANGE_NAMES_MINUTE = ["USA Stocks", "FOREX", "Cryptocurrencies"]


class RequestExchangeData(RequestData):
    # Maps eodhd.com API column names to their DB column name equivalent
    # (https://eodhd.com/api/exchanges-list/ returns Name, Code, OperatingMIC, Country, Currency,
    # CountryISO2, CountryISO3 - created_at is generated by the DB, not part of the API response)
    _API_COLUMN_TO_DB_COLUMN = {
        "Name":         tables.Exchange.Columns.NAME,
        "Code":         tables.Exchange.Columns.EXCHANGE_CODE,
        "OperatingMIC": tables.Exchange.Columns.OPERATING_MIC,
        "Country":      tables.Exchange.Columns.COUNTRY,
        "Currency":     tables.Exchange.Columns.CURRENCY,
        "CountryISO2":  tables.Exchange.Columns.COUNTRY_ISO_2,
        "CountryISO3":  tables.Exchange.Columns.COUNTRY_ISO_3,
    }

    def __init__(self, api_token: str, time_frame: TimeFrame):
        self._api_token: str = api_token
        self._time_frame: TimeFrame = time_frame

    @staticmethod
    def _get_url_for_exchanges_data() -> str:
        return Url.Address.EXCHANGES_LIST

    def _get_url_params_for_exchanges_data(self) -> dict[str, str]:
        return {
            Url.Param.API_TOKEN: self._api_token,
            Url.Param.FMT: Url.Value.JSON,
        }

    def _check_exchange_data(self, df_exchanges: pd.DataFrame):
        if not self._has_columns(df_exchanges, list(self._API_COLUMN_TO_DB_COLUMN)):
            raise CompatibilityError("Exchange data has unexpected structure!")

    def _format_exchanges_data(self, df_exchanges: pd.DataFrame) -> pd.DataFrame:
        if self._time_frame == TimeFrame.DAILY:
            df_exchanges_filtered = df_exchanges[df_exchanges["Name"].isin(_EXCHANGE_NAMES_EOD)]
        else:
            df_exchanges_filtered = df_exchanges[df_exchanges["Name"].isin(_EXCHANGE_NAMES_MINUTE)]
        df_exchanges_filtered = df_exchanges_filtered.rename(columns=self._API_COLUMN_TO_DB_COLUMN)
        return df_exchanges_filtered

    def get(self) -> pd.DataFrame:
        """Requests exchanges meta data"""
        url_exchanges = self._get_url_for_exchanges_data()
        params        = self._get_url_params_for_exchanges_data()
        # Requests data
        data_exchanges = self._request_data_from_url(url_exchanges, params)
        # Creates and formats df
        df_exchanges = pd.DataFrame(data_exchanges)
        self._check_exchange_data(df_exchanges)
        df_exchanges_filtered = self._format_exchanges_data(df_exchanges)

        return df_exchanges_filtered